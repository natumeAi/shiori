// Generates the embedded Brotli static dictionary from third_party/brotli.
//
// Usage:
//   dart run tool/fonts/brotli_dictionary.dart
//   dart run tool/fonts/brotli_dictionary.dart --check
//
// The output contains only base64 of the pinned dictionary; the SHA-256 is
// verified before writing and again by the decoder at first use.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

const _source = 'third_party/brotli/dictionary.bin';
const _target = 'lib/features/reader/engine/layout/brotli_dictionary_data.dart';
const _sha = '20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70';

String _generate(List<int> bytes) {
  final encoded = base64Encode(bytes);
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/fonts/brotli_dictionary.dart. Do not edit.')
    ..writeln(
      '// Source: third_party/brotli/dictionary.bin (RFC 7932 Appendix A).',
    )
    ..writeln(
      '// SHA-256: $_sha; ${bytes.length} bytes; MIT (see third_party).',
    )
    ..writeln()
    ..writeln('/// Base64 of the RFC 7932 static dictionary.')
    ..writeln('const String brotliDictionaryBase64 =');
  for (var i = 0; i < encoded.length; i += 76) {
    final end = (i + 76).clamp(0, encoded.length);
    // The terminator joins the last literal, matching `dart format` output.
    final terminator = end == encoded.length ? ';' : '';
    buffer.writeln("    '${encoded.substring(i, end)}'$terminator");
  }
  return buffer.toString();
}

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final file = File(_source);
  if (!file.existsSync()) {
    stderr.writeln('missing $_source');
    exitCode = 2;
    return;
  }
  final bytes = file.readAsBytesSync();
  final digest = sha256.convert(bytes).toString();
  if (digest != _sha || bytes.length != 122784) {
    stderr.writeln('dictionary mismatch: $digest ${bytes.length}');
    exitCode = 2;
    return;
  }
  final content = _generate(bytes);
  final target = File(_target);
  if (check) {
    if (!target.existsSync() || target.readAsStringSync() != content) {
      stderr.writeln('$_target is not up to date');
      exitCode = 1;
      return;
    }
    stdout.writeln('dictionary ok (${bytes.length} bytes, $digest)');
    return;
  }
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(content);
  stdout.writeln('wrote $_target (${bytes.length} bytes, $digest)');
}
