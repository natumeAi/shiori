// RFC 7932 static dictionary transforms (Appendix B).
extension _Dictionary on _BrotliState {
  Uint8List _dictionaryWord(int wordId, int length) {
    if (length < 4 || length > 24) throw _malformed;
    final nbits = _ndBits[length];
    final count = 1 << nbits;
    final index = wordId & (count - 1);
    final transform = wordId >> nbits;
    if (transform > 120) throw _malformed;
    final start = _dictOffset[length] + index * length;
    if (start + length > _dictionary.length) throw _malformed;
    return _applyTransform(
      Uint8List.fromList(_dictionary.sublist(start, start + length)),
      transform,
    );
  }

  Uint8List _applyTransform(Uint8List word, int id) {
    var value = word;
    final type = _transformData[3 * id + 1];
    if (type == 1) {
      _fermentFirst(value);
    } else if (type == 2) {
      _fermentAll(value);
    } else if (type >= 3 && type <= 11) {
      final n = type - 2;
      value = Uint8List.sublistView(value, n < value.length ? n : value.length);
    } else if (type >= 12 && type <= 20) {
      final n = type - 11;
      value = Uint8List.sublistView(
        value,
        0,
        value.length > n ? value.length - n : 0,
      );
    }
    final prefix = utf8.encode(_affix[_transformData[3 * id]]);
    final suffix = utf8.encode(_affix[_transformData[3 * id + 2]]);
    return Uint8List(prefix.length + value.length + suffix.length)
      ..setAll(0, prefix)
      ..setAll(prefix.length, value)
      ..setAll(prefix.length + value.length, suffix);
  }

  static void _fermentFirst(Uint8List word) {
    if (word.isNotEmpty) _ferment(word, 0);
  }

  static void _fermentAll(Uint8List word) {
    var i = 0;
    while (i < word.length) {
      i += _ferment(word, i);
    }
  }

  static int _ferment(Uint8List word, int pos) {
    if (word[pos] < 192) {
      if (word[pos] >= 97 && word[pos] <= 122) word[pos] ^= 32;
      return 1;
    }
    if (word[pos] < 224) {
      if (pos + 1 < word.length) word[pos + 1] ^= 32;
      return 2;
    }
    if (pos + 2 < word.length) word[pos + 2] ^= 5;
    return 3;
  }
}

