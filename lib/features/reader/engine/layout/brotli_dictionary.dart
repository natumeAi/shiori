final List<int> _dictOffset = () {
  final values = List<int>.filled(25, 0);
  for (var len = 0; len < 24; len++) {
    final words = len < 4 ? 0 : 1 << _ndBits[len];
    values[len + 1] = values[len] + len * words;
  }
  return values;
}();
